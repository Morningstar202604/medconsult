"""临床要素引擎：资料完备度评分 + 红旗危急征象扫描（确定性规则，可解释、可审计）。

医院场景价值：
  1. 会诊前告知"资料缺什么"（引导补充，而不是让模型猜）；
  2. 危急征象在专家发言前就横幅警示（安全优先）；
  3. 报告中呈现"资料完备度 X/6"，让置信度有可解释依据。
"""
import re

# 资料六要素
ELEMENTS = [
    ("年龄性别", r"\d{1,3}\s*岁|(?:男|女)性|male|female"),
    ("病程时间", r"\d+\s*(小时|天|日|周|月|年)|chronic|acute"),
    ("既往史", r"既往|病史|高血压|糖尿病|冠心病|肝炎|结核"),
    ("用药过敏", r"服药|用药|服用|口服|静滴|静注|皮下注射|过敏|药物|mg/|mg\s|qd|bid|tid|服(?!务)"),
    ("辅助检查", r"心电图|CT|MRI|B超|彩超|化验|胸片|造影|血常规|检查见|报告"),
    ("生命体征", r"血压|体温|心率|呼吸|脉搏|血氧"),
]

# 红旗危急征象（出现即建议紧急就医评估）
RED_FLAGS = [
    (r"胸[痛闷].{0,12}(冷汗|大汗|放射|濒死)|冷汗.{0,8}胸[痛闷]", "疑似急性冠脉综合征表现（胸痛伴冷汗/放射）"),
    (r"意识(模糊|障碍|不清)|昏迷|谵妄", "意识障碍——需紧急评估（脑血管事件、代谢危象等）"),
    (r"突发.{0,6}剧烈头痛|撕裂样.{0,6}痛|刀割样.{0,6}痛", "剧痛性质描述，警惕主动脉夹层/蛛网膜下腔出血"),
    (r"呼吸困难|气促.{0,6}加重|不能平卧|端坐呼吸", "呼吸困难/端坐呼吸——警惕心衰、肺部急症"),
    (r"咯血|呕血|黑便|便血", "消化道/呼吸道出血表现——需紧急处理"),
    (r"晕厥|黑矇|跌倒发作", "晕厥/黑矇——警惕心源性与栓塞事件"),
    (r"体温\s*3[9-9]\.\d|高热(不退|持续)", "高热——警惕脓毒症"),
    (r"剧烈腹痛|板状腹|腹肌紧张", "急腹症征象——需外科紧急评估"),
    (r"一侧.{0,6}(无力|瘫痪)|言语不清|口角歪斜", "卒中征象（FAST）——时间窗内需紧急溶栓评估"),
    (r"(血糖|血糖仪).{0,8}(微量|测不出)|低血糖表现|大汗.{0,6}手抖", "警惕低血糖危象"),
]


def completeness(text):
    """资料完备度：返回 {score, total, present, missing}。"""
    t = text or ""
    present, missing = [], []
    for name, pat in ELEMENTS:
        (present if re.search(pat, t, re.I) else missing).append(name)
    return {"score": len(present), "total": len(ELEMENTS),
            "present": present, "missing": missing}


def red_flags(text):
    """红旗扫描：返回 [描述...]（确定性规则命中）。"""
    t = text or ""
    return [msg for pat, msg in RED_FLAGS if re.search(pat, t)]


def assess(text):
    """一次扫描同时返回完备度与红旗。"""
    return {"completeness": completeness(text), "red_flags": red_flags(text)}
